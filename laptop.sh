#!/bin/bash
# Run on your laptop after setup.sh on a Mac mini: adds the mini-<n> command and logs that Mac mini in to Claude.
#   /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/candix-com/mac-mini-setup/main/laptop.sh)"
set -euo pipefail

read -rp "Which Mac mini? Type its number: " number </dev/tty
[[ $number =~ ^[1-9][0-9]*$ ]] || { echo "Type just a number, like 1."; exit 1; }

# "ssh mini-<n>" opens the Mac mini's terminal tabs (tmux), as dev; they keep running when you disconnect
sed -i '' '/^# mac-mini-setup begin$/,/^# mac-mini-setup end$/d' ~/.ssh/config 2>/dev/null || true
mkdir -p ~/.ssh
# Make sure the existing file ends with a newline so our block starts on its own line
[[ -s ~/.ssh/config && -n "$(tail -c1 ~/.ssh/config)" ]] && echo >> ~/.ssh/config
cat >> ~/.ssh/config <<'EOF'
# mac-mini-setup begin
Host mini-*
  User dev
  StrictHostKeyChecking accept-new
  ServerAliveInterval 30
  RequestTTY yes
  RemoteCommand /opt/homebrew/bin/tmux new-session -A -s main
# mac-mini-setup end
EOF

# The command you type
cat > "/opt/homebrew/bin/mini-$number" <<EOF
#!/usr/bin/env bash
# Generated by mac-mini-setup's laptop.sh. Opens the terminal of mini-$number.
# -a keeps your laptop's SSH keys away from the agents
ssh -a -o ConnectTimeout=8 mini-$number; rc=\$?
# If the connection dropped, tmux couldn't switch off mouse reporting: do it here
printf '\e[?1000l\e[?1002l\e[?1003l\e[?1004l\e[?1006l\e[?1015l\e[?2004l\e[?25h'
[[ \$rc -eq 255 ]] && echo "Couldn't reach mini-$number. Is Tailscale on?"
exit \$rc
EOF
chmod +x "/opt/homebrew/bin/mini-$number"

echo "Last step: log in to Claude. Click the link it shows, approve, paste the code back."
echo "Once you see Claude's prompt, type /exit."
read -rp "Press Enter to continue..." </dev/tty
ssh -a -o RemoteCommand=none -t "mini-$number" '~/.local/bin/claude' </dev/tty || true
echo "Done. Type: mini-$number"
